void test_sm3_hash() {
  int rlt;
  uint8_t* rlt_out = NULL;
  size_t rlt_len = 0;

  nbl_sm3_context_t ctx;

  rlt = nbl_sm3_init(&ctx, NBL_SM3_HASH, NULL, 0);
  if (NBL_SM_SUCCESS != rlt) {
    TLOGI("failed, err=%#x\n", rlt);
    exit(1);
  }

  rlt = nbl_sm3_update(&ctx, hash_data_sm3_a1_in,
                       ARRAY_SIZE(hash_data_sm3_a1_in));
  if (NBL_SM_SUCCESS != rlt) {
    TLOGI("failed, err=%#x\n", rlt);
    goto failed;
  }

  rlt_len = ARRAY_SIZE(hash_data_sm3_a1_in);
  rlt_out = (uint8_t*)calloc(1, rlt_len);

  rlt = nbl_sm3_final(&ctx, rlt_out, rlt_len);
  if (NBL_SM_SUCCESS != rlt) {
    TLOGI("failed, err=%#x\n", rlt);
    goto failed;
  }

  CHECK_BUF_EQ(hash_data_sm3_a1_out, rlt_out, rlt_len, "compare");

  free(rlt_out);

  rlt = nbl_sm3_destroy(&ctx);
  if (NBL_SM_SUCCESS != rlt) {
    TLOGI("failed, err=%#x\n", rlt);
    exit(1);
  }

  return;

failed:
  if (rlt_out)
    free(rlt_out);

  nbl_sm3_destroy(&ctx);

  exit(1);
}

