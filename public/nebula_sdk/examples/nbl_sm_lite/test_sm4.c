void test_sm4_ecb_nopad() {
  int rlt;
  nbl_sm4_context_t ctx;
  uint8_t* rlt_out = NULL;
  size_t rlt_len;

  rlt =
      nbl_sm4_init(&ctx, NBL_SM4_ECB_NOPAD, NBL_SM_MODE_ENCRYPT,
                   ciph_data_sm4_key1, ARRAY_SIZE(ciph_data_sm4_key1), NULL, 0);
  if (NBL_SM_SUCCESS != rlt) {
    TLOGI("failed, err=%#x\n", rlt);
    exit(1);
  }

  rlt_len = ARRAY_SIZE(ciph_data_sm4_in1);
  rlt_out = (uint8_t*)calloc(1, rlt_len);

  rlt = nbl_sm4_update(&ctx, ciph_data_sm4_in1, ARRAY_SIZE(ciph_data_sm4_in1),
                       rlt_out);
  if (NBL_SM_SUCCESS != rlt) {
    TLOGI("failed, err=%#x\n", rlt);
    goto failed;
  }

  // Check
  CHECK_BUF_EQ(ciph_data_sm4_ecb_nopad_out1, rlt_out, rlt_len, "compare");

  free(rlt_out);
  rlt_out = NULL;

  rlt = nbl_sm4_final(&ctx);
  if (NBL_SM_SUCCESS != rlt) {
    TLOGI("failed, err=%#x\n", rlt);
    goto failed;
  }

  rlt = nbl_sm4_destroy(&ctx);
  if (NBL_SM_SUCCESS != rlt) {
    TLOGI("failed, err=%#x\n", rlt);
    exit(1);
  }

  return;

failed:
  if (rlt_out)
    free(rlt_out);

  nbl_sm4_destroy(&ctx);

  exit(1);
}

