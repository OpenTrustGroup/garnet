basepath=$(cd `dirname $0`; pwd)
config_file_name=provision.config

function help()
{
    echo "Create a configuration file for the provision HA."
    echo "-o The path to the certificate and key. The directory structure of the certificate and key is generated by the create_key.sh script.
             It is also the output path of the configuration file."
    echo "-h show help."
}

# parse the arguments of scripts
ARGS=`getopt -o ho: -n "$0" -- "$@"`
if [ $? != 0 ]; then
    echo "Arguments are error."
    exit 1
fi

eval set -- "${ARGS}"

while true
do
    case "$1" in
        -o)
            base_out_path=$2
            shift 2
            ;;
        --)
            shift
            break
            ;;
        -h)
            help
            exit 0
            ;;
        *)
            help
            exit 1
            ;;
    esac
done

if [ -z "$base_out_path" ]; then
    echo "Create configuration file failed. -o param is empty."
    exit 1
fi

mkdir -p $base_out_path

#create config

read -p "Please input tsm id:" tsm_id
read -p "Please input sp id:" sp_id
read -p "Please input sd name:" sd_name
#read -p "Please input hee name:" hee_name
hee_name=test_tee_name

if [ -z "$tsm_id" ]; then
    echo "Create configuration file failed. TSM id is empty."
    help
    exit 1
fi

if [ -z "$tsm_id" ]; then
    echo "Create configuration file failed. SP id is empty."
    help
    exit 1
fi

if [ -z "$sd_name" ]; then
    echo "Create configuration file failed. SD name is empty."
    help
    exit 1
fi

if [ -z "$hee_name" ]; then
    echo "Create configuration file failed. HEE name is empty."
    help
    exit 1
fi

echo "creat config file start: "$config_file_name

if [ -f "$base_out_path/$config_file_name" ];then
    rm -f $base_out_path/$config_file_name
fi

echo "tsm_id=$tsm_id" >> $base_out_path/$config_file_name
echo "sp_id=$sp_id" >> $base_out_path/$config_file_name
echo "sd_name=$sd_name" >> $base_out_path/$config_file_name
echo "hee_name=$hee_name" >> $base_out_path/$config_file_name

echo "creat config file finish:" $base_out_path/$config_file_name
