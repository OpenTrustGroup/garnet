### start HEE/TEE/REE in qemu

set -e; [[ "${TRACE}" ]] && set -x

# On default, use "debug" build.
declare IMAGE_BUILD="debug"
declare ENABLE_NET="true"
declare QEMU_VIRTIO_V9FS_FLAGS=""
declare QEMU_DEBUG_FLAGS=""

declare QEMU_HEE_RAM="1024"
declare QEMU_REE1_RAM="1536" # Linux Kernel
declare QEMU_REE2_RAM="128"   # Linux Rootfs
declare QEMU_ION_RAM="32"    # Reserved memory for ION heap
declare QEMU_TEE_RAM="448"
declare QEMU_CPU_NUM="4"
declare QEMU_GIC_VERSION="3"
declare INPUT_IMAGE=""

declare CMDLINE=""
declare TEST_MODE=""
declare CPU_MODEL="cortex-a53"
declare QEMU_ACTIVE_HYP="off"
declare QEMU_TEE_SYSTEM_MODE="1"	# 0: 3 systems (tee,hee,ree)  1: 2 systems (tee,ree)
declare QEMU_VMID="0"

function usage() {
  printf '%s: [-N] [-m] [-r] [-h]\n' "$0"
  printf '  -N            disable QEMU networking via tun/tap. Default is enable.\n'
  printf '  -m <abs-dir>  enable QEMU host file-sharing via 9p. abs-dir must be absolute path.\n'
  printf '  -r            run the "release" build. Default is "debug" build.\n'
  printf '  -s            start the qemu with gdb and freeze on start, waiting for input "c" to continue.\n'
  printf '  -a            disable ASLR.\n'
  printf '  -i            input Nebula qemu image. the image usually generated by PDK\n'
  printf '  -t <arg>      test mode, no terminals, no graphic, run in docker\n'
  printf '  -x            using TMUX as QEMU console (default: gnome-terminal or xterm)\n'
  printf '  -9            QEMU emulate ARMv9 cpu cortex-a710 (default: '${CPU_MODEL}')\n'
  printf '  -z            run QEMU with active hyp simulation enabled.\n'
  printf '  -h            show help.\n'
}

while getopts "ai:rsNm:htx9z:" opt; do
  case "${opt}" in
    a)
      CMDLINE+="aslr.disable=true "
      ;;
    t)
      TEST_MODE="true"
      TEST_ARGS=${OPTARG}
      QEMU_DEBUG_FLAGS=""
      ;;
    i)
      INPUT_IMAGE=${OPTARG}
      if [[ ! -e $INPUT_IMAGE ]]; then
        echo "${INPUT_IMAGE} not found!"
        exit 1
      fi
      ;;
    N)
      ENABLE_NET="false"
      ;;
    m)
      QEMU_VIRTIO_V9FS_FLAGS=" -fsdev local,security_model=none,id=fsdev0,path=${OPTARG} -device virtio-9p-pci,id=fs0,fsdev=fsdev0,mount_tag=hostshare,vmid=${QEMU_VMID}"
      ;;
    r)
      IMAGE_BUILD="release"
      ;;
    s)
      QEMU_DEBUG_FLAGS="-s -S"
      ;;
    x)
      if [[ ! -z "${TMUX}" ]]; then
        readonly tmux="$(command -v tmux 2>/dev/null)"
      else
        echo "Warning: tmux is not running, ignore."
      fi
      ;;
    9)
      CPU_MODEL="cortex-a710"
      ;;
    z)
      QEMU_ACTIVE_HYP="on"
      QEMU_TEE_SYSTEM_MODE="0"
      QEMU_VMID="1"
      ;;
    h) usage 1>&2 ; exit 0 ;;
    *) usage 1>&2 ; exit 1 ;;
  esac
done

# get the path of this command, and then get the path of sdk.
# - CMD_DIR should be "<sdk>/run/"
CMD_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
SDK_HOME=$(dirname $CMD_DIR)

# find the qemu directory.
# The source of binary executable qemu is in "//third_party/qemu".
if [ -z "$FUCHSIA_DIR" ]; then # in SDK
  QEMU_DIR=$CMD_DIR/qemu
  QEMU_BIN=${QEMU_DIR}/qemu-x86_64-linux/bin
  QEMU_EXE=${QEMU_BIN}/qemu-system-aarch64
  QEMU_DATA=${QEMU_DIR}/data

  readonly SOC_TERM_PATH="${QEMU_DIR}/soc_term"
  readonly ATF_BUILDROOT="${QEMU_DATA}/build-atf"

  if [ "$IMAGE_BUILD" = "debug" ]; then
    declare QEMU_ZIRCON_KERNEL_BIN="${QEMU_DATA}/bootdata-combo-qemu.bin"
    declare QEMU_TEE_KERNEL_BIN="${QEMU_DATA}/bootdata-combo-qemu-tee.bin"
  else
    declare QEMU_ZIRCON_KERNEL_BIN="${QEMU_DATA}/bootdata-combo-qemu-rel.bin"
    declare QEMU_TEE_KERNEL_BIN="${QEMU_DATA}/bootdata-combo-qemu-tee-rel.bin"
  fi

  declare QEMU_START_DHCP_SVR=${QEMU_BIN}/start-dhcp-server.sh

else # In Fuchsia env.

  FUCHSIA_BUILD_DIR=${FUCHSIA_OUT_DIR}/arm64
  ZIRCON_BUILD_DIR=${FUCHSIA_OUT_DIR}/build-zircon/build-venus-hee
  ZIRCON_RELEASE_BUILD_DIR=${FUCHSIA_OUT_DIR}/build-zircon-release/build-venus-hee

  QEMU_BIN=${FUCHSIA_OUT_DIR}/qemu-x86_64-linux/bin
  QEMU_EXE=${QEMU_BIN}/qemu-system-aarch64

  readonly SOC_TERM_PATH="${FUCHSIA_DIR}/third_party/soc_term"
  readonly ATF_BUILDROOT="${FUCHSIA_OUT_DIR}/build-atf"

  if [ "$IMAGE_BUILD" = "debug" ]; then
    declare QEMU_ZIRCON_KERNEL_BIN="${FUCHSIA_OUT_DIR}/venus-hee/arm64/bootdata-combo-qemu-virt.bin"
    declare QEMU_TEE_KERNEL_BIN="${FUCHSIA_OUT_DIR}/venus-tee/arm64/bootdata-combo-qemu-virt.bin"
  else
    declare QEMU_ZIRCON_KERNEL_BIN="${FUCHSIA_OUT_DIR}/venus-hee/arm64/bootdata-combo-qemu-virt-rel.bin"
    declare QEMU_TEE_KERNEL_BIN="${FUCHSIA_OUT_DIR}/venus-tee/arm64/bootdata-combo-qemu-virt-rel.bin"
  fi

  declare QEMU_START_DHCP_SVR=${FUCHSIA_DIR}/scripts/start-dhcp-server.sh
fi

readonly gnome_terminal="$(command -v gnome-terminal 2>/dev/null)"
readonly xterm="$(command -v xterm 2>/dev/null)"
declare QEMU_FUCHSIA_ARGS=""
declare QEMU_SERIAL_FLAGS="-serial tcp:localhost:54320 -serial tcp:localhost:54321 -serial tcp:localhost:54322"

declare QEMU_VIRTIO_NET_FLAGS="-net none"

if [[ -n $TERM ]]; then
    CMDLINE+="TERM=$TERM "
fi

if [[ ! -z ${INPUT_IMAGE} ]]; then
    QEMU_ZIRCON_KERNEL_BIN=${INPUT_IMAGE}
fi

# Add entropy to the kernel
CMDLINE+="kernel.entropy-mixin=$(head -c 32 /dev/urandom | shasum -a 256 | awk '{ print $1 }') "

# Don't 'reboot' the emulator if the kernel crashes
CMDLINE+="kernel.halt-on-panic=true "

# Remove/Disable unneeded functions
CMDLINE+="virtcon.disable=true "
# - User can run "nblruncmd xxx" in REE, transfer the command to HEE and run it.
#CMDLINE+="netsvc.disable=true "
#CMDLINE+="ktrace.bufsize=1 "
CMDLINE+="kernel.oom.enable=false "
CMDLINE+="earlycon=pl011,0x09001000 console=ttyAMA0 "
CMDLINE+="fbcon=map:2 " # Disable Linux Framebuffer

#####################################################################
#### Nebula Driver Settings
#####################################################################
# nbl_display
CMDLINE+="driver.nbl_display.bti=0:0 "
CMDLINE+="driver.nbl_display.mmio=0xf000000:0x1000 "
CMDLINE+="driver.nbl_display.irq=230:0 "
#CMDLINE+="driver.nbl_display.log=+trace "
# nbl_touch
CMDLINE+="driver.nbl_touch.bti=0:0 "
CMDLINE+="driver.nbl_touch.mmio=0xf001000:0x1000 "
CMDLINE+="driver.nbl_touch.irq=231:0 "
#CMDLINE+="driver.nbl_touch.log=+trace "
CMDLINE+="driver.nbl_touch.i2c_id=0 "
# nbl_drvtest
CMDLINE+="driver.nbl_drvtest.bti=0:0 "
CMDLINE+="driver.nbl_drvtest.mmio=0xf002000:0x1000,0xf003000:0x1000 "
CMDLINE+="driver.nbl_drvtest.irq=232:0 "
#CMDLINE+="driver.nbl_drvtest.log=+trace "

enable-network()
{
    IFNAME="qemu-3"
    HASH=$(echo ${IFNAME} | shasum)
    SUFFIX=$(for i in {0..2}; do echo -n :${HASH:$(( 2 * $i )):2}; done)
    MAC=",mac=52:54:00$SUFFIX"
    QEMU_VIRTIO_NET_FLAGS=" -netdev type=tap,ifname=${IFNAME},script=${QEMU_START_DHCP_SVR},downscript=no,id=net0"
    QEMU_VIRTIO_NET_FLAGS+=" -device virtio-net-pci,netdev=net0${MAC},vmid=${QEMU_VMID}"
    sudo tunctl -u $(whoami) -t ${IFNAME}
    sudo ifconfig ${IFNAME} down
}

launch-terminal() {
  if [[ ! -z "${tmux}" ]]; then
    nc -z  127.0.0.1 ${1} || ${tmux} new-window -a -n "${2}" ${SOC_TERM_PATH}/soc_term ${1}
  elif [[ ! -z "${gnome_terminal}" ]];then
    nc -z  127.0.0.1 ${1} || ${gnome_terminal} -t "${2}" -x ${SOC_TERM_PATH}/soc_term ${1} &
  elif [[ ! -z "${xterm}" ]];then
    nc -z  127.0.0.1 ${1} || ${xterm} -title "${2}" -e ${BASH} -c "${SOC_TERM_PATH}/soc_term ${1}" &
  else
    echo "Error: could not find gnome-terminal nor xterm"
    exit 1
  fi
}

# If start qemu with debug and freeze for continue, prompt users to input "c" commmand to continue.
function run-help() {
  echo
  echo \* QEMU is now waiting to start the execution
  echo \* Start execution with either a \'c\' followed by \<enter\> in the QEMU console or
  echo \* attach a debugger and continue from there.
  echo
}

wait-for-ports() {
  while ! nc -z 127.0.0.1 ${1} || ! nc -z 127.0.0.1 ${2}; do sleep 1; done
}

# Because the kernel and user image are differet from release and debug build,
# so relink the bl33.bin.
function relink_atf_images() {
  ln -sf ${QEMU_TEE_KERNEL_BIN} bl32.bin
  ln -sf ${QEMU_ZIRCON_KERNEL_BIN} bl33.bin
}

launch_qemu() {

  cd ${ATF_BUILDROOT}/images
  relink_atf_images

  if [ "$ENABLE_NET" = "true" ]; then
    enable-network
  fi

  declare QEMU_EXTRA_ARGS="-semihosting-config enable,target=native -d unimp -no-acpi -vga none -device virtio-gpu-pci,vmid=${QEMU_VMID},xres=1080,yres=1920 -device virtio-tablet-pci,vmid=${QEMU_VMID} -serial mon:stdio"

  ${QEMU_EXE} \
    -machine virt,secure=on,virtualization=true \
    -machine gic_version=${QEMU_GIC_VERSION} \
    -machine hee_ram_size=${QEMU_HEE_RAM} \
    -machine ree1_ram_size=${QEMU_REE1_RAM} \
    -machine ree2_ram_size=${QEMU_REE2_RAM} \
    -machine tee_ram_size=${QEMU_TEE_RAM} \
    -machine ion_ram_size=${QEMU_ION_RAM} \
    -machine active_hyp=${QEMU_ACTIVE_HYP} \
    -machine tee_system_mode=${QEMU_TEE_SYSTEM_MODE} \
    -cpu ${CPU_MODEL} \
    -smp ${QEMU_CPU_NUM} \
    -m $(($QEMU_HEE_RAM + $QEMU_REE1_RAM + $QEMU_TEE_RAM)) \
    -bios ${ATF_BUILDROOT}/images/bl1.bin  -vga none \
    -semihosting-config enable,target=native -d unimp \
    -kernel ${QEMU_ZIRCON_KERNEL_BIN} -no-acpi \
    -append "${CMDLINE}" \
    ${QEMU_FUCHSIA_ARGS} \
    ${QEMU_VIRTIO_NET_FLAGS} \
    ${QEMU_VIRTIO_V9FS_FLAGS} \
    ${QEMU_SERIAL_FLAGS} \
    ${QEMU_DEBUG_FLAGS} \
    ${QEMU_EXTRA_ARGS} \

}

if [ -z "$TEST_MODE" ]; then
    launch-terminal 54322 "REE"
    launch-terminal 54321 "TEE"
    launch-terminal 54320 "HYP"
    wait-for-ports 54320 54321
else
    # expect scripts will find available ports
    QEMU_SERIAL_FLAGS="${TEST_ARGS}"
fi

if [ -n "$QEMU_DEBUG_FLAGS" ]; then
  run-help
fi

trap cleanup INT ERR EXIT
cleanup() {
  ERRNO=$?
  IFNAME="qemu-3"
  if [[ -n "$(ifconfig -a | grep ${IFNAME})" ]]; then
    sudo tunctl -d "${IFNAME}" &> /dev/null
    DNSMASQ="$(pgrep -fo "interface=${IFNAME}" | tr '\n' ' ')"
    [[ -n "${DNSMASQ}" ]] && sudo kill ${DNSMASQ} &> /dev/null
  fi
  return $ERRNO
}

launch_qemu
